function createHistory(city, dates, locations = []) {
  return (dates || []).map((date, index) => ({
    date,
    location:
      locations[index] ||
      (index === 0 ? `${city} Regional Blood Centre` : `${city} Community Donation Camp ${index + 1}`),
    units: 1,
  }));
}

function donor(seed) {
  return {
    id: seed.id,
    name: seed.name,
    age: seed.age,
    bloodGroup: seed.bloodGroup,
    country: seed.country,
    state: seed.state,
    city: seed.city,
    phone: seed.phone,
    weight: seed.weight,
    hasRecentIllness: Boolean(seed.hasRecentIllness),
    onMedication: Boolean(seed.onMedication),
    lastDonation: seed.lastDonation || "Not donated yet",
    eligible: Boolean(seed.eligible),
    donationHistory: createHistory(seed.city, seed.historyDates, seed.historyLocations),
  };
}

